globalThis.MediaAppI18n = (() => {
  let language = 'da';
  const reverse = new Map(Object.entries(messages).map(([en, da]) => [da, en]));
  const initial = [];
  const attributes = [];
  const originalTitle = typeof document !== 'undefined' ? document.title : '';
  function t(source, values = {}) {
    if (typeof source !== 'string') return source;
    const key = source.trim();
    const en = Object.hasOwn(messages, key) ? key : reverse.get(key) || key;
    const text = language === 'da' ? messages[en] || en : en;
    return (source.match(/^\s*/)[0] + text + source.match(/\s*$/)[0]).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  }
  function locale() { return language === 'da' ? 'da-DK' : 'en-GB'; }
  function setLanguage(value) {
    language = value === 'en' ? 'en' : 'da';
    if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = language;
    if (typeof document !== 'undefined' && originalTitle) document.title = t(originalTitle);
    for (const [node, source] of initial) if (node.isConnected) node.nodeValue = t(source);
    for (const [node, name, source] of attributes) if (node.isConnected) node.setAttribute(name, t(source));
  }
  // Capture only the static document, before account names, file names or API data
  // are rendered. Never observe or translate arbitrary user/remote DOM content.
  if (typeof document !== 'undefined' && document.createTreeWalker) {
    const walker = document.createTreeWalker(document.body, 4);
    for (let node; (node = walker.nextNode());) {
      if (!node.parentElement?.closest('script,style,code') && node.nodeValue.trim()) initial.push([node, node.nodeValue]);
    }
    for (const node of document.querySelectorAll('[placeholder],[aria-label],[title]')) {
      for (const name of ['placeholder','aria-label','title']) if (node.hasAttribute(name)) attributes.push([node, name, node.getAttribute(name)]);
    }
  }
  return {t, setLanguage, locale};
})();

